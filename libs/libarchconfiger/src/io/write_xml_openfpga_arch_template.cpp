namespace arkangel {

/********************************************************************
 * A writer to output a VPR arch object to XML format
 *
 * Return 0 if successful
 * Return 1 if there are more serious bugs in the architecture
 * Return 2 if fail when creating files
 *******************************************************************/
int write_xml_openfpga_arch_template(const char* fname, const ArchGen& arch_gen) {
  std::string timer_msg =
    std::string("Write openfpga arch template to file: ") + std::string(fname);
  vtr::ScopedStartFinishTimer timer(timer_msg.c_str());

  int num_err = 0;

  pugi::xml_document out_xml;

  pugi::xml_node root_node = out_xml.append_child(XML_OPENFPGA_ARCH_ROOT_NODE_NAME);

  root_node.append_child(pugi::node_comment)
    .set_value("!-- This file is automatically generated!!! Do not modify by hand!");

  num_err += arch_gen.add_xml_openfpga_arch_node(root_node);

  out_xml.save_file(fname);

  return num_err ? openfpga::CMD_EXEC_FATAL_ERROR : openfpga::CMD_EXEC_SUCCESS;
}

}  // End of namespace arkangel
