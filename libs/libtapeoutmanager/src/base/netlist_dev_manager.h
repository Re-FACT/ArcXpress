/**
 * The data structure stores data for ArcXpress benchmark suites
 * It is used to provide necessary information to categorize spot benchmark files
 */
class NetlistDevManager {
 public: /* -- Types -- */
  /* The type of step names */
  enum class e_fabric_type {
    DP = 0,
    ULTIMATE,
    NUM_TYPES /* Count the number of types, also this is an invalid type */
  };
  /* Define all the file types including input and outputs
   * The file type is used for file tracking during various development process/steps
   * IMPORTANT: the first 4 elements must match the e_file_type of TapeoutManager !!!
   */
  enum class e_file_type {
    VPR_ARCH = 0,                      /* VPR architecture file */
    OPENFPGA_ARCH,                     /* Openfpga architecture file */
    OPENFPGA_GNTWK_ARCH,               /* OpenFPGA global network architecture */
    OPENFPGA_CKBUF_LOC_MAP,            /* Openfpga default simulation setting file */
    DESIGN_VAR,                        /* Design variable file */
    OPENFPGA_SIM_SETTING,              /* Openfpga default simulation setting file */
    OPENFPGA_BITSTREAM_SETTING,        /* Openfpga default simulation setting file */
    OPENFPGA_BITSTREAM_SETTING_APPEND, /* Openfpga default simulation setting file */
    OPENFPGA_TILE_CONFIG,              /* Openfpga tile configuration file */
    OPENFPGA_PCF_XML, /* Openfpga XML-based PCF, this is a dummy version which is applied when
                         benchmark does not have one */
    VPR_SDC, /* Vpr sdc file, this is a dummy version which is applied when benchmark does not have
                one */
    OPENFPGA_PCF,     /* Openfpga XML-based PCF, this is a dummy version which is applied when
                             benchmark does not have one */
    FINAL_FABRIC_KEY, /* Final fabric key which is generated based on the handcrafted and reference
                       */
    REF_MODULE_NAME,
    CRAFTED_MODULE_NAME,     /* Crafted module names by user */
    RRG,                     /* Routing resource graph, which is cached for fast vpr-run */
    PDL,                     /* Placement delay lookup, which is cached for fast vpr-run  */
    RLA,                     /* Router lookahead, which is cached for fast vpr-run */
    TILE_REF,                /* Tile reference file which is auto generated */
    PIN_TABLE,               /* Pin table file which is auto generated */
    MUX_MODULE_FILE,         /* Mux module list which is used by synthesis */
    CONFIG_MEM_MODULE_FILE,  /* Configuration memory module list which is used by synthesis */
    FABRIC_PIN_PHY_LOC_FILE, /* Fabric pin physical location file which is used by physical design
                              */
    FABRIC_HIERARCHY_FILE,   /* Fabric hierarchy file which is used by physical design */
    UNDRIVEN_MAKEUP_KEY,
    BSCAN_MAKEUP_KEY,
    CLKN_MAKEUP_KEY,
    SYNTH_PDK_CONFIG,
    SYNTH_BLOCK_QOR_FILE,
    SYNTH_TILE_QOR_FILE,
    BASE_BITSTREAM_FILE,
    BITSTREAM_XML_FILE,
    BITSTREAM_DIST_FILE,
    ARCH_TIMING,
    FLOORPLAN_SHAPING_TXT,
    NUM_TYPES /* Count the number of types, also this is an invalid type */
  };
  /* Type of scripts */
  enum class e_script_type {
    OPENFPGA_SCRIPT_BITGEN = 0, /* Openfpga shell script for synthetic bitstream generation */
    OPENFPGA_SCRIPT_GCLKBITGEN, /* Openfpga shell script for synthetic bitstream generation */
    OPENFPGA_SCRIPT_GRSTBITGEN, /* Openfpga shell script for synthetic bitstream generation */
    OPENFPGA_SCRIPT_BASEBITGEN, /* Openfpga shell script for synthetic bitstream generation */
    OPENFPGA_SCRIPT_FABRIC,     /* Openfpga shell script for netlist generation */
    NUM_TYPES                   /* Count the number of types, also this is an invalid type */
  };
  /* Type of netlists */
  enum class e_netlist_type {
    RAW_RTL = 0, /* The original netlist generated by openfpga */
    RTL,         /* The netlist generated by netlist makeup based on raw rtl */
    GL,          /* The gate-level netlist after synthesis is applied on rtl */
    NUM_TYPES    /* Count the number of types, also this is an invalid type */
  };

 private: /* -- Types for internal use only -- */
 public:  /* -- Constructors -- */
  NetlistDevManager(const TapeoutManager& to_mgr, const std::string& run_name,
                    const PdkManager& pdk_mgr);

 public: /* -- Aggregators -- */
  std::array<e_fabric_type, size_t(e_fabric_type::NUM_TYPES)> fabrics() const;
  std::array<e_netlist_type, size_t(e_netlist_type::NUM_TYPES)> netlist_types() const;
  std::vector<size_t> gclock_sweep_ids() const;
  std::vector<size_t> greset_sweep_ids() const;

 public: /* -- Accessors -- */
  std::string opt_stage_all_str() const;
  /* Print the path to the file and show the content */
  int show_file(const e_fabric_type& fb_type, const e_file_type& f_type, const bool& verbose) const;
  /* Generate the path to input/output files for each step */
  std::string file(const e_fabric_type& fb_type, const e_file_type& f_type,
                   const bool& verbose) const;
  std::string gclock_bitstream_value_file(const size_t& clk_sweep_id, const bool& verbose) const;
  std::string greset_bitstream_value_file(const size_t& rst_sweep_id, const bool& verbose) const;
  openfpga::BasicPort gclk_port() const;
  openfpga::BasicPort grst_port() const;
  std::string openfpga_script_file(const e_script_type& runtime_type) const;
  std::string report_dir() const;
  std::string rr_gsb_dir(const e_fabric_type& fb_type) const;
  std::string netlist_release_dir(const e_netlist_type& nlist_type) const;
  std::string netlist_dir(const e_fabric_type& fb_type, const e_netlist_type& nlist_type) const;
  std::string netlist_block_dir(const e_fabric_type& fb_type,
                                const e_netlist_type& nlist_type) const;
  std::string netlist_tile_dir(const e_fabric_type& fb_type,
                               const e_netlist_type& nlist_type) const;
  std::string synth_dir() const;
  std::string synth_sdc_ccff_dir() const;
  std::string synth_sdc_dir() const;
  std::string synth_runtime_dir() const;
  std::string synth_compile_config_file() const;
  std::string synth_analyze_config_file() const;
  std::string report_timing_dirpath(const e_fabric_type& fb_type,
                                    const e_netlist_type& nlist_type) const;
  std::string ppa_summary_dirpath(const e_fabric_type& fb_type,
                                  const e_netlist_type& nlist_type) const;
  /* Generate the path to temporary files under runtime directories for each step */
  std::string openfpga_runtime_file(const e_fabric_type& fb_type, const e_file_type& f_type,
                                    const e_script_type& runtime_type, const bool& verbose) const;
  /* This is used for sweeping global signals only */
  std::string openfpga_runtime_sweep_file(const e_fabric_type& fb_type, const e_file_type& f_type,
                                          const e_script_type& runtime_type, const size_t& sweep_id,
                                          const bool& verbose) const;
  std::string openfpga_runtime_script_file(const e_fabric_type& fb_type,
                                           const e_script_type& runtime_type,
                                           const bool& verbose) const;
  /* This is used for sweeping global signals only */
  std::string openfpga_runtime_sweep_script_file(const e_fabric_type& fb_type,
                                                 const e_script_type& runtime_type,
                                                 const size_t& sweep_id, const bool& verbose) const;
  std::string openfpga_runtime_log_file(const e_fabric_type& fb_type,
                                        const e_script_type& runtime_type,
                                        const bool& verbose) const;
  int import_external_netlists(const e_fabric_type& fb_type, const bool& verbose) const;
  int append_flag_to_netlist(const e_fabric_type& fb_type, const bool& verbose) const;
  int netlist_makeup(const e_fabric_type& fb_type, const std::string& netlist_makeup_bin_path,
                     const bool& duplicate_netlist_only, const bool& verbose) const;
  int ccff_makeup(const std::string& ccff_makeup_bin_path, const bool& verbose) const;
  int setup_rtl_synth(const bool& verbose) const;
  int synth_rtl(const std::string& synth_bin_path, const bool& dryrun, const size_t& max_jobs,
                const bool& verbose) const;
  int parse_post_synth_block_report(const std::string& synth_bin_path, const size_t& max_jobs,
                                    const bool& verbose) const;
  int gen_common_gl(const e_fabric_type& fb_type, const bool& verbose) const;
  int gen_gl(const bool& verbose) const;
  int analyze_tile_ppa(const std::string& synth_bin_path, const bool& dryrun,
                       const size_t& max_jobs, const bool& verbose) const;
  int parse_post_synth_tile_report(const std::string& synth_bin_path, const size_t& max_jobs,
                                   const bool& verbose) const;
  /* Initialize the netlist directory with proper files */
  int init_netlist_dir(const e_fabric_type& fb_type, const bool& verbose) const;
  int init_netlist_dir_all(const bool& verbose) const;
  /* Optimize netlists */
  int optimize_netlist(const std::string& ccff_makeup_bin_path, const std::string& synth_bin_path,
                       const std::string& stage_sel, const bool& dryrun, const size_t& max_jobs,
                       const bool& verbose) const;
  /* Analyze netlists */
  int coarse_analyze_netlist(const std::string& synth_bin_path, const bool& dryrun,
                             const size_t& max_jobs, const bool& verbose) const;
  /* Print stats for configuration time and bitstream sizes */
  int show_config_stats(const float& pclk_freq, const std::string& report_file_path,
                        const int& precision, const bool& verbose = false) const;
  /* Save results */
  std::vector<std::string> result_files(const TapeoutManager::e_substep_name& s_step,
                                        const bool& verbose) const;
  std::string md5_yaml_file() const;
  int save_results(const std::vector<TapeoutManager::e_substep_name>& s_steps,
                   const bool& verbose) const;
  int check_results(const bool& verbose) const;
  /* Export netlist to a package */
  int export_netlist(const std::string& fname, const bool& force_overwrite,
                     const bool& verbose) const;

 public: /* -- Mutators -- */
  void set_route_chan_width(const size_t& val);
  void set_ccff_max_fanout(const size_t& val);
  void set_netlist_makeup_config_file(const std::string& val);
  void set_ccff_makeup_buf_config_file(const std::string& val);
  bool add_file(const e_fabric_type& fb_type, const e_file_type& f_type, const std::string& f_name);
  void add_ip_file(const std::string& f_name, const TapeoutManager::e_ip_file_format& f_fmt);
  void add_ip_gl_file(const std::string& f_name);
  bool add_openfpga_script(const e_script_type& script_type, const std::string& f_name);
  void set_source_arch_dir(const std::string& arch_dir);
  void set_source_pdk_dir(const std::string& pdk_dir);
  void set_source_netlist_makeup_dir(const std::string& nmakeup_dir);
  void set_source_synth_sdc_dir(const std::string& sdc_dir);
  void set_source_synth_strategy_file(const std::string& val);
  void set_source_floorplan_strategy_file(const std::string& val);
  void add_pdk_verilog(const std::string& f_name);
  bool add_netlist_flag(const std::string& flag, const std::string& val);
  void set_default_corner(const std::string& val);
  /* Generate netlists */
  int generate_netlist(const e_fabric_type& fb_type, const BenchmarkPacket& bm_pkt,
                       const std::string& openfpga_bin_path,
                       const std::string& netlist_makeup_bin_path,
                       const bool& enable_netlist_makeup, const bool& verbose);
  int generate_netlist_all(const BenchmarkPacket& bm_pkt, const std::string& openfpga_bin_path,
                           const std::string& netlist_makeup_bin_path,
                           const bool& enable_netlist_makeup, const bool& verbose);
  /* Generate base bitstream */
  int generate_base_bitstream(const BenchmarkPacket& bm_pkt, const std::string& openfpga_bin_path,
                              const bool& verbose);
  /* Generate base bitstream */
  int generate_clock_sweep_bitstream(const BenchmarkPacket& bm_pkt,
                                     const std::string& openfpga_bin_path, const bool& verbose);
  int generate_reset_sweep_bitstream(const BenchmarkPacket& bm_pkt,
                                     const std::string& openfpga_bin_path, const bool& verbose);

  /* Perform a coarse floorplan on the efpga fabric */
  int coarse_floorplan(const std::string& rpt_fpath, const std::string& shaping_rpt,
                       const size_t& precision, const bool& verbose, const e_fabric_type& fb_type,
                       const std::string& strategy_file = "");

 public: /* -- Validator -- */
  bool valid_fabric_type(const e_fabric_type& fb_type) const;
  bool valid_netlist_type(const e_netlist_type& nlist_type) const;
  bool valid_file_type(const e_file_type& f_type) const;
  bool valid_script_type(const e_script_type& f_type) const;
  bool valid_opt_stage(const std::string& stage, const bool& verbose) const;
  bool required_file_type(const TapeoutManager::e_arch_file_type& f_type) const;

 public: /* Public utility */
  std::filesystem::path project_home_dir() const;
  e_file_type convert_file_type(const TapeoutManager::e_arch_file_type& to_f_type) const;
  e_script_type convert_script_type(const TapeoutManager::e_script_type& to_f_type) const;

  e_file_type str2file_type(const std::string& str, const bool& verbose = false) const;
  std::string file_type_all2str() const;

  e_fabric_type str2fabric_type(const std::string& str, const bool& verbose = false) const;
  std::string fabric_type2str(const e_fabric_type& type, const bool& verbose = false) const;
  std::string fabric_type_all2str() const;

  e_netlist_type str2netlist_type(const std::string& str, const bool& verbose = false) const;
  std::string netlist_type2str(const e_netlist_type& type, const bool& verbose = false) const;
  std::string netlist_type_all2str() const;

 private: /* Private utility */
  void init(const std::string& booting_root, const std::string& root_path,
            const std::string& proj_name, const std::string& family_name,
            const std::string& run_name, const PdkManager& pdk_mgr,
            const std::string& openfpga_error_conf_file, const std::string& py_bin_path);
  /* Get the path to the file that are generated by global port sweeping runs */
  std::string global_port_sweep_file(const e_file_type& f_type, const e_script_type& runtime_type,
                                     const size_t& sweep_id, const bool& verbose) const;
  /* A complete process to copy a file from a source to a destination. Support to copy as a symbolic
   * link It will create directories if does not exist Sanity checks will be applied:
   * - Source file does not exist
   * - Destination file does not exist
   */
  int copy_file_with_mkdir(const std::string& src_file, const std::string& des_file,
                           const bool& symlink, const bool& verbose) const;
  int init_runtime_dir(const e_fabric_type& fb_type, const e_script_type& runtime_type,
                       const bool& verbose) const;
  /* This is used for sweeping global signals only */
  int init_runtime_sweep_dir(const e_fabric_type& fb_type, const e_script_type& runtime_type,
                             const size_t& sweep_id, const bool& verbose) const;
  int init_runtime_script(const e_fabric_type& fb_type, const e_script_type& runtime_type,
                          const BenchmarkPacket& bm_pkt, const bool& verbose) const;
  /* This is used for sweeping global signals only */
  int init_runtime_sweep_script(const e_fabric_type& fb_type, const e_script_type& runtime_type,
                                const size_t& sweep_id, const BenchmarkPacket& bm_pkt,
                                const bool& verbose) const;
  int runtime_exec_openfpga(const e_fabric_type& fb_type, const e_script_type& runtime_type,
                            const std::string& openfpga_bin_path, const bool& verbose);
  /* This is used for sweeping global signals only */
  int runtime_exec_sweep_openfpga(const e_fabric_type& fb_type, const e_script_type& runtime_type,
                                  const size_t& sweep_id, const std::string& openfpga_bin_path,
                                  const bool& verbose);
  /* This is used for sweeping global signals only */
  int check_global_port_sweep_result_files(const std::vector<e_file_type>& f_types_to_check,
                                           const e_script_type& runtime_type,
                                           const size_t& sweep_id, const bool& verbose) const;
  int check_result_files(const e_fabric_type& fb_type,
                         const std::vector<e_file_type>& f_types_to_check,
                         const bool& verbose) const;
  int generate_fabric_netlist(const std::string& src_dir, const std::string& o_fname,
                              const bool& verbose) const;

  int setup_gl_placeholder_dir(const bool& verbose) const;

 private: /* -- Private Validator -- */
  void check_valid_fabric_type(const e_fabric_type& fb_type) const;
  void check_valid_file_type(const e_file_type& f_type) const;
  void check_valid_netlist_type(const e_netlist_type& nlist_type) const;

 private: /* -- Internal data -- */
  /* Basic information */
  std::string booting_root_;
  std::string root_path_;
  std::string proj_name_;
  std::string family_name_;
  std::string run_name_;

  /* Source file lists */
  std::string src_arch_dir_;
  std::string src_pdk_dir_;
  std::array<std::string, size_t(e_script_type::NUM_TYPES)> src_openfpga_script_files_;
  std::map<e_file_type, std::string> src_openfpga_setting_files_;
  std::string src_netlist_makeup_dir_;
  std::string src_synth_sdc_dir_;
  std::string src_synth_strategy_file_;
  std::string src_floorplan_strategy_file_;
  std::vector<std::string> ip_files_;
  std::vector<TapeoutManager::e_ip_file_format> ip_file_formats_;
  std::vector<std::string> ip_gl_files_;
  std::vector<std::string> pdk_verilog_files_;
  std::map<std::string, std::string> netlist_flags_;
  std::string default_corner_;
  std::string netlist_makeup_config_file_;
  std::string ccff_makeup_buf_config_file_;

  /* Arch variables */
  size_t route_chan_width_;
  size_t ccff_max_fanout_;

  /* Floorplan results */
  TileQor tile_qor_;

  /* Constants */
  std::array<std::string, size_t(e_fabric_type::NUM_TYPES)> FABRIC_TYPE_STRING_;
  std::array<std::string, size_t(e_netlist_type::NUM_TYPES)> NETLIST_TYPE_STRING_;
  std::array<std::string, size_t(e_file_type::NUM_TYPES)> FILE_NAMES_;
  std::array<std::string, size_t(e_file_type::NUM_TYPES)> FILE_TAGS_;
  std::array<std::string, size_t(e_file_type::NUM_TYPES)> FILE_TYPE_NAMES_;
  std::array<std::string, size_t(e_file_type::NUM_TYPES)> VAR_NAMES_;
  std::array<std::string, size_t(e_script_type::NUM_TYPES)> SCRIPT_NAMES_;
  std::array<std::string, size_t(e_script_type::NUM_TYPES)> SCRIPT_TYPE_STRING_;

  /* Directory names */
  std::string SUBDIR_NAME_;
  std::string ARCH_DIR_NAME_;
  std::string NETLIST_DIR_NAME_;
  std::string NETLIST_BLOCK_DIR_NAME_;
  std::string NETLIST_TILE_DIR_NAME_;
  std::string NETLIST_TECHSRC_DIR_NAME_;
  std::string NETLIST_CUSTOM_MODULE_DIR_NAME_;
  std::string SWEEP_DIR_PREFIX_;

  std::string SYNTH_DIR_NAME_;
  std::string SYNTH_CONFIG_DIR_NAME_;
  std::string SYNTH_CUSTOM_DIR_NAME_;
  std::string SYNTH_SDC_DIR_NAME_;
  std::string SYNTH_CCFF_DIR_NAME_;
  std::string SYNTH_RUNTIME_DIR_NAME_;

  std::string RPT_DIR_NAME_;
  std::string RPT_AREA_DIR_NAME_;
  std::string RPT_TIMING_DIR_NAME_;
  std::string RPT_SUMMARY_DIR_NAME_;
  std::string RPT_BITSTREAM_DIST_DIR_NAME_;
  std::string PDK_DIR_NAME_;
  std::string RRGSB_DIR_NAME_;
  std::string OPENFPGA_RUNDIR_NAME_;
  std::string PINTABLE_RUNDIR_NAME_;

  /* Variables names in openfpga shell scripts */
  std::string ARCH_VAR_FILE_;
  std::string OPENFPGA_RRGSB_DIR_VAR_NAME_;
  std::string OPENFPGA_NETLIST_DIR_VAR_NAME_;
  std::string VPR_BLIF_VAR_NAME_;
  std::string VPR_FABRIC_VAR_NAME_;
  std::string VPR_ROUTE_CHAN_W_VAR_NAME_;

  std::string FABRIC_NETLIST_FILENAME_;
  std::string NETLIST_FLAG_FILENAME_;
  std::string NETLIST_FPGA_TOP_FILENAME_;
  std::string NETLIST_FPGA_CORE_FILENAME_;
  std::string NETLIST_INCLUDE_FILENAME_;
  std::string OPENFPGA_LOG_FILENAME_;
  std::string SYNTH_COMPILE_CONFIG_FILENAME_;
  std::string SYNTH_ANALYZE_CONFIG_FILENAME_;
  std::string ARCH_TIMING_FILE_PREFIX_;
  std::string ARCH_TIMING_FILE_POSTFIX_;
  std::string MD5_FILENAME_;

  /* Stage names */
  std::string OPT_STAGE_ALL_;
  std::string OPT_STAGE_SETUP_;
  std::string OPT_STAGE_SYNTH_;
  std::string OPT_STAGE_GEN_GL_;

  /* Python */
  std::string PYTHON_COMMAND_;

  /* Local cache */
  const PdkManager* pdk_mgr_;
  LogErrorChecker openfpga_log_checker_;

  /* Flag */
  mutable bool is_valid_;
};

