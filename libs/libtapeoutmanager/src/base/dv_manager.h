namespace arcxpress {

/**
 * The data structure stores data for ArkAngel benchmark suites
 * It is used to provide necessary information to categorize spot benchmark files
 */
class DvManager {
 public: /* -- Types -- */
  /* Type of netlists */
  enum class e_netlist_type {
    RTL = 0,  /* The netlist generated by netlist makeup based on raw rtl */
    GL,       /* The gate-level netlist after synthesis is applied on rtl */
    PL,       /* The post-layout-level netlist after synthesis is applied on rtl */
    NUM_TYPES /* Count the number of types, also this is an invalid type */
  };
  /* Type of simulator */
  enum class e_simulator_type {
    VCS = 0,
    MODELSIM, /* The modelsim  */
    QUESTA,   /* The questa  */
    NUM_TYPES /* Count the number of types, also this is an invalid type */
  };
  /* Type of waveform */
  enum class e_waveform_type {
    NONE = 0,
    FSDB,
    VCD,
    NUM_TYPES /* Count the number of types, also this is an invalid type */
  };

  /* Type of files */
  enum class e_file_type {
    OUT_BLIF = 0,               /* The output blif file by Front-end */
    OUT_VERILOG_REWRITE,        /* The output verilog file by Front-end for bus group generation */
    OUT_VERILOG,                /* The output verilog file by Front-end */
    VPR_ARCH,                   /* VPR architecture file */
    OPENFPGA_ARCH,              /* Openfpga architecture file */
    OPENFPGA_GNTWK_ARCH,        /* OpenFPGA global network architecture */
    DESIGN_VAR,                 /* Design variable file */
    OPENFPGA_SIM_SETTING,       /* Openfpga default simulation setting file */
    OPENFPGA_BITSTREAM_SETTING, /* Openfpga default simulation setting file */
    OPENFPGA_TILE_CONFIG,       /* Openfpga tile configuration file */
    OPENFPGA_PCF_XML, /* Openfpga XML-based PCF, this is a dummy version which is applied when
                         benchmark does not have one */
    VPR_SDC, /* Vpr sdc file, this is a dummy version which is applied when benchmark does not have
                one */
    OPENFPGA_PCF,           /* PCF file provided by user */
    OPENFPGA_FINAL_PCF_XML, /* Openfpga XML-based PCF, this is a dummy version which is applied when
                         benchmark does not have one */
    OPENFPGA_CKBUF_LOC_MAP,
    OPENFPGA_FINAL_PCF_XML4DV, /* Openfpga XML-based PCF, this is a dummy version which is applied
                         when benchmark does not have one */
    FINAL_FABRIC_KEY, /* Final fabric key which is generated based on the handcrafted and reference
                       */
    CRAFTED_MODULE_NAME,      /* Crafted module names by user */
    RRG,                      /* Routing resource graph, which is cached for fast vpr-run */
    PDL,                      /* Placement delay lookup, which is cached for fast vpr-run  */
    RLA,                      /* Router lookahead, which is cached for fast vpr-run */
    VPR_NET_FILE,             /* .net file outputted by vpr */
    VPR_PLACE_FILE,           /* .place file outputted by vpr */
    VPR_ROUTE_FILE,           /* .route file outputted by vpr */
    BASE_BITSTREAM_XML_FILE,  /* Plain text file for bitstream */
    BITSTREAM_TEXT_FILE,      /* Plain text file for bitstream */
    BITSTREAM_XML_FILE,       /* XML file for bitstream */
    BITSTREAM_PIN_MAP_FILE,   /* Pin mapping file related to the bitstream */
    PRECONFIG_TESTBENCH_FILE, /* Preconfigured testbench file */
    FULL_TESTBENCH_FILE,      /* Preconfigured testbench file */
    BUS_GROUP_FILE,           /* Auto-generated bus group file */
    BUS_GROUP_TASK_FILE,      /* task config file for bus group file auto-gen */
    ARCH_TIMING,
    WAVEFORM_FSDB,
    NUM_TYPES /* Count the number of types, also this is an invalid type */
  };
  /* Type of scripts */
  enum class e_script_type {
    OPENFPGA_SCRIPT_PRECONFIGTB = 0, /* Openfpga shell script for netlist generation */
    OPENFPGA_SCRIPT_FULLTB,          /* Openfpga shell script for netlist generation */
    YOSYS_SCRIPT_REWRITE,            /* Openfpga shell script for bus group generation */
    NUM_TYPES                        /* Count the number of types, also this is an invalid type */
  };
  /* Type of cocotb files */
  enum class e_cocotb_file_type {
    TOP = 0, /* Top-level testbench */
    MAKEFILE,
    BITSTREAM_BASE,
    BITSTREAM_VALUE,
    UTIL,
    NUM_TYPES /* Count the number of types, also this is an invalid type */
  };

 private: /* -- Types for internal use only -- */
 public:  /* -- Constructors -- */
  DvManager(const TapeoutManager& to_mgr, const std::string& run_name,
            const ArchEvalManager& ae_mgr, const NetlistDevManager& nd_mgr);

 public: /* -- Aggregators -- */
  std::vector<DvManager::e_netlist_type> netlist_types() const;

 public: /* -- Accessors -- */
  std::filesystem::path project_home_dir() const;
  int init_dir(const bool& verbose) const;
  std::string report_timing_dirpath(const e_netlist_type& nlist_type) const;
  std::string report_power_dirpath(const e_netlist_type& nlist_type) const;
  std::string ppa_summary_dirpath(const e_netlist_type& nlist_type) const;

  int setup_cocotb(const std::string& cocotb_util_bin_path,
                   const std::string& cocotb_force_bitstrm_bin_path, const size_t& max_jobs,
                   const size_t& new_thread_wait_time, const size_t& sim_thread_wait_time,
                   const std::string& corner, const bool& verbose) const;
  int run_preconfig_cocotb(const std::string& cocotb_util_bin_path,
                           const std::string& cocotb_makefile_incl_fpath,
                           const e_netlist_type& nlist_type, const e_simulator_type& sim_type,
                           const e_waveform_type& wfm_type, const size_t& max_jobs,
                           const size_t& new_thread_wait_time, const size_t& sim_thread_wait_time,
                           const size_t& log_check_wait_time, const std::string& corner,
                           const std::string& benchmark_name, const bool& verbose) const;
  /*overloaded function for dynamic power analysis for a single benchmark*/
  int run_preconfig_cocotb_benchmark(
    const std::string& cocotb_util_bin_path, const std::string& cocotb_makefile_incl_fpath,
    const BenchmarkSuiteId& st_id, const std::string& benchmark_name,
    const DvManager::e_netlist_type& nlist_type, const DvManager::e_simulator_type& sim_type,
    const DvManager::e_waveform_type& wfm_type, const size_t& max_jobs,
    const size_t& new_thread_wait_time, const size_t& sim_thread_wait_time,
    const size_t& log_check_wait_time, const std::string& corner, const bool& verbose) const;
  std::vector<std::string> result_files(const bool& verbose) const;
  std::string md5_yaml_file() const;
  int save_results(const bool& verbose) const;
  int check_results(const bool& verbose) const;

 public: /* -- Mutators -- */
  void set_route_chan_width(const size_t& val);
  void set_fabric_name(const std::string& val);
  bool add_yosys_script(const e_script_type& script_type, const std::string& f_name);
  bool add_openfpga_script(const e_script_type& script_type, const std::string& f_name);
  bool add_file(const e_file_type& f_type, const std::string& f_name);
  bool init_netlist_source_dir(const bool& verbose);
  int generate_testbench(const std::string& openfpga_bin_path, const std::string& bgg_bin_path,
                         const std::string& corner, const bool& verbose);
  int generate_preconfig_testbench(const std::string& openfpga_bin_path,
                                   const std::string& bgg_bin_path, const std::string& corner,
                                   const bool& verbose);
  int run_preconfig_tb_gen(const BenchmarkSuiteId& st_id, const BenchmarkId& bm_id,
                           const std::string& openfpga_bin_path, const std::string& bgg_bin_path,
                           const std::string& corner, const bool& verbose);

 public: /* -- Validator -- */
  bool required_script_type(const TapeoutManager::e_script_type& f_type) const;
  bool required_file_type(const TapeoutManager::e_arch_file_type& f_type) const;
  bool required_netlist_type(const NetlistDevManager::e_netlist_type& f_type) const;
  bool valid_script_type(const e_script_type& f_type) const;
  bool valid_file_type(const e_file_type& f_type) const;
  void check_valid_file_type(const e_file_type& f_type) const;

 public: /* Public utility */
  e_script_type convert_script_type(const TapeoutManager::e_script_type& to_f_type) const;
  e_file_type convert_file_type(const TapeoutManager::e_arch_file_type& to_f_type) const;
  e_netlist_type convert_netlist_type(const NetlistDevManager::e_netlist_type& to_f_type) const;
  TapeoutManager::e_substep_name convert_netlist_type_to_substep_name(
    const e_netlist_type& nlist_type) const;

  e_netlist_type str2netlist_type(const std::string& str, const bool& verbose = false) const;
  e_cocotb_file_type str2cocotb_file_type(const std::string& str,
                                          const bool& verbose = false) const;
  e_simulator_type str2simulator_type(const std::string& str, const bool& verbose = false) const;
  e_waveform_type str2waveform_type(const std::string& str, const bool& verbose = false) const;
  std::string file(const BenchmarkSuiteId& st_id, const BenchmarkId& bm_id,
                   const e_file_type& f_type, const std::string& corner, const bool& verbose) const;
  std::string cocotb_runtime_file(const BenchmarkSuiteId& st_id, const BenchmarkId& bm_id,
                                  const std::string& corner,
                                  const std::filesystem::path& fname) const;
  std::filesystem::path preconfig_sim_runtime_dir() const;

 private: /* Private utility */
  void init(const std::string& root_path, const std::string& proj_name,
            const std::string& family_name, const std::string& run_name,
            const ArchEvalManager& ae_mgr, const NetlistDevManager& nd_mgr,
            const std::string& openfpga_error_conf_file, const std::string& cell_lib_path,
            const std::string& py_bin_path, const std::string& py_site_packages_path);
  int copy_file_with_mkdir(const std::string& src_file, const std::string& des_file,
                           const bool& sym_link, const bool& verbose) const;
  std::filesystem::path dv_dir() const;
  std::filesystem::path netlist_dir(const e_netlist_type& nlist_type) const;
  std::filesystem::path full_sim_runtime_dir() const;
  std::filesystem::path bitstream_dir() const;
  std::filesystem::path output_subdir(const BenchmarkSuiteId& st_id, const BenchmarkId& bm_id,
                                      const std::string& corner) const;
  std::string openfpga_script_file(const e_script_type& runtime_type) const;
  std::string openfpga_runtime_script_file(const BenchmarkId& bm_id,
                                           const e_script_type& runtime_type,
                                           const std::string& corner, const bool& verbose) const;
  std::string openfpga_runtime_dir(const e_script_type& runtime_type, const BenchmarkId& bm_id,
                                   const std::string& corner, const bool& verbose) const;
  std::string openfpga_runtime_file(const e_file_type& f_type, const e_script_type& runtime_type,
                                    const BenchmarkId& bm_id, const std::string& corner,
                                    const bool& verbose) const;

  int init_runtime_script(const BenchmarkSuiteId& st_id, const BenchmarkId& bm_id,
                          const e_script_type& runtime_type, const std::string& bgg_bin_path,
                          const std::string& corner, const bool& verbose) const;
  int write_bus_group_runtime_task_yaml(const BenchmarkSuiteId& st_id, const BenchmarkId& bm_id,
                                        const e_script_type& runtime_type,
                                        const std::string& corner, const bool& verbose) const;
  int runtime_exec_openfpga(const BenchmarkId& bm_id, const e_script_type& runtime_type,
                            const std::string& openfpga_bin_path, const std::string& corner,
                            const bool& verbose);
  int check_result_files(const BenchmarkSuiteId& st_id, const BenchmarkId& bm_id,
                         const std::vector<e_file_type>& f_types_to_check,
                         const std::string& corner, const bool& verbose) const;
  int init_runtime_dir(const BenchmarkSuiteId& st_id, const BenchmarkId& bm_id,
                       const e_script_type& runtime_type, const std::string& corner,
                       const bool& verbose) const;

  int write_cocotb_task_file(const BenchmarkSuiteId& st_id,
                             const std::string& cocotb_force_bitstrm_bin_path,
                             const std::string& corner, size_t& cnt, const bool& verbose) const;
  int run_cocotb_setup(const BenchmarkSuiteId& st_id, const std::string& cocotb_util_bin_path,
                       const size_t& max_jobs, const size_t& new_thread_wait_time,
                       const size_t& sim_thread_wait_time, const std::string& corner,
                       const bool& verbose) const;
  std::filesystem::path cocotb_task_file(const BenchmarkSuiteId& st_id,
                                         const std::string& corner) const;
  std::string cocotb_runtime_netlist_dir(const BenchmarkSuiteId& st_id, const BenchmarkId& bm_id,
                                         const std::string& corner,
                                         const e_netlist_type& nlist_type) const;

  int run_cocotb_preconfig_task(
    const BenchmarkSuiteId& st_id, const std::string& cocotb_util_bin_path,
    const std::string& cocotb_makefile_incl_fpath, const DvManager::e_netlist_type& nlist_type,
    const DvManager::e_simulator_type& sim_type, const DvManager::e_waveform_type& wfm_type,
    const size_t& max_jobs, const size_t& new_thread_wait_time, const size_t& sim_thread_wait_time,
    const size_t& log_check_wait_time, const std::string& corner, const std::string& benchmark_name,
    const bool& verbose) const;

  int run_cocotb_preconfig_task_benchmark(
    const BenchmarkSuiteId& st_id, const std::string& benchmark_name,
    const std::string& cocotb_util_bin_path, const std::string& cocotb_makefile_incl_fpath,
    const DvManager::e_netlist_type& nlist_type, const DvManager::e_simulator_type& sim_type,
    const DvManager::e_waveform_type& wfm_type, const size_t& max_jobs,
    const size_t& new_thread_wait_time, const size_t& sim_start_wait_time,
    const size_t& log_check_wait_time, const std::string& corner, const bool& verbose) const;

 private: /* -- Private Validator -- */
  bool valid_netlist_type(const e_netlist_type& nlist_type) const;
  std::string netlist_type2str(const e_netlist_type& type, const bool& verbose = false) const;
  std::string netlist_type_all2str() const;
  void check_valid_netlist_type(const e_netlist_type& nlist_type) const;

  bool valid_cocotb_file_type(const e_cocotb_file_type& nlist_type) const;
  std::string cocotb_file_type2str(const e_cocotb_file_type& type,
                                   const bool& verbose = false) const;
  std::string cocotb_file_type_all2str() const;
  void check_valid_cocotb_file_type(const e_cocotb_file_type& nlist_type) const;

  bool valid_simulator_type(const e_simulator_type& sim_type) const;
  std::string simulator_type2str(const e_simulator_type& type, const bool& verbose = false) const;
  std::string simulator_type_all2str() const;
  void check_valid_simulator_type(const e_simulator_type& sim_type) const;

  bool valid_waveform_type(const e_waveform_type& wfm_type) const;
  std::string waveform_type2str(const e_waveform_type& type, const bool& verbose = false) const;
  std::string waveform_type_all2str() const;
  void check_valid_waveform_type(const e_waveform_type& wfm_type) const;

 private: /* -- Internal data -- */
  /* Basic information */
  std::string root_path_;
  std::string family_name_;
  std::string proj_name_;
  std::string run_name_;
  std::string cell_lib_path_;

  /* Source file lists */
  std::array<std::string, size_t(e_script_type::NUM_TYPES)> src_script_files_;
  std::map<e_file_type, std::string> src_openfpga_setting_files_;

  /* Arch variables */
  std::string fabric_name_;
  size_t route_chan_width_;

  /* Script variable names */
  std::string VPR_FABRIC_VAR_NAME_;
  std::string VPR_ROUTE_CHAN_W_VAR_NAME_;
  std::string VPR_BLIF_VAR_NAME_;
  std::string OPENFPGA_PYTHON_EXEC_VAR_NAME_;
  std::string OPENFPGA_BUS_GROUP_GEN_EXEC_VAR_NAME_;

  /* Dependencies */
  const ArchEvalManager* ae_mgr_;
  const NetlistDevManager* nd_mgr_;

  /* Constants */
  std::array<std::string, size_t(e_script_type::NUM_TYPES)> SCRIPT_TYPE_STRING_;
  std::array<std::string, size_t(e_file_type::NUM_TYPES)> FILE_NAMES_;
  std::array<std::string, size_t(e_file_type::NUM_TYPES)> VAR_NAMES_;
  std::array<std::string, size_t(e_netlist_type::NUM_TYPES)> NETLIST_TYPE_STRING_;
  std::array<std::string, size_t(e_cocotb_file_type::NUM_TYPES)> COCOTB_FILE_TYPE_STRING_;
  std::array<std::string, size_t(e_simulator_type::NUM_TYPES)> SIMULATOR_TYPE_STRING_;
  std::array<std::string, size_t(e_waveform_type::NUM_TYPES)> WAVEFORM_TYPE_STRING_;

  std::string PYTHON_COMMAND_;
  std::string PYTHON_SITE_PACKAGES_PATH_;

  std::string DV_SUBDIR_NAME_;
  std::string ARCH_DIR_NAME_;
  std::string NETLIST_DIR_NAME_;
  std::string DV_DIR_NAME_;
  std::string RPT_DIR_NAME_;
  std::string RPT_TIMING_DIR_NAME_;
  std::string RPT_POWER_DIR_NAME_;
  std::string RPT_SUMMARY_DIR_NAME_;
  std::string PRECONFIG_TB_DIR_NAME_;
  std::string PRECONFIG_TB_TASK_DIR_NAME_;
  std::string FULL_TB_DIR_NAME_;
  std::string OPENFPGA_RUNDIR_NAME_;
  std::string MD5_FILENAME_;

  std::string OPENFPGA_LOG_FILENAME_;
  std::string OPENFPGA_SCRIPT_FILENAME_;
  std::string COCOTB_TASK_FILENAME_POSTFIX_;
  std::string COCOTB_BASE_BITSTREAM_XML_FILENAME_;
  std::string ARCH_TIMING_FILE_PREFIX_;
  std::string ARCH_TIMING_FILE_POSTFIX_;

  LogErrorChecker yosys_log_checker_;
  LogErrorChecker openfpga_log_checker_;

  /* Flag */
  mutable bool is_valid_;
};

}  // namespace arcxpress
