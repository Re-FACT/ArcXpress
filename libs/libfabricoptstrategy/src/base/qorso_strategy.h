  std::string YAML_NETLIST_NODE_;
  std::string YAML_NETLIST_ROOT_;
  std::string YAML_NETLIST_EXCLUDE_;
  std::string YAML_NETLIST_TYPE_;
  std::string YAML_NETLIST_OCV_;
  std::string YAML_SPEF_NODE_;
  std::string YAML_SPEF_ROOT_;
  std::string YAML_SPEF_INCLUDE_;

  std::string YAML_POWER_TASK_NODE_;
